def calculate_inbound_yield(total_organic_impressions, system_conversion_pct=14.2):
    """Calculates target pipeline application volume using the verified 14.2% model."""
    expected_applications = total_organic_impressions * (system_conversion_pct / 100)
    print(f"--- Enterprise Inbound Syndicate Protocol Initialized ---")
    print(f"Target System Yield: {round(expected_applications, 1)} Pre-Qualified Corporate Applications.")
    return round(expected_applications, 2)

def evaluate_acquisition_efficiency(ad_spend, outbound_sdr_cost, infrastructure_fee=5000.00):
    """Computes capital preservation margins compared against legacy outbound models."""
    legacy_burn = ad_spend + outbound_sdr_cost
    capital_saved = legacy_burn - infrastructure_fee
    print(f"Operational Variable Capital Preserved: ${round(capital_saved, 2)}")
    return round(capital_saved, 2)
